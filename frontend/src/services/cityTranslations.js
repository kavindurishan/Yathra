/**
 * Normalizes input name and returns translation object or null
 */
export function getCityTranslationObj(rawName) {
  if (!rawName || typeof rawName !== 'string') return null;
  const cleaned = rawName.trim();
  const lower = cleaned.toLowerCase();

  // 1. Direct match
  if (CITY_TRANSLATIONS[lower]) {
    return CITY_TRANSLATIONS[lower];
  }

  // 2. Strip common location suffixes: e.g. " (Main Terminal)", " Bus Stand", " Fort"
  const stripped = lower
    .replace(/\s*\(.*?\)\s*/g, '')
    .replace(/\s+(bus stand|bus terminal|goods shed|interchange|junction|halt|central|station)\b/g, '')
    .trim();

  if (CITY_TRANSLATIONS[stripped]) {
    return CITY_TRANSLATIONS[stripped];
  }

  // 3. Partial substring matching against known city keys
  for (const [key, value] of Object.entries(CITY_TRANSLATIONS)) {
    if (lower.startsWith(key) || lower.includes(key)) {
      return value;
    }
  }

  return null;
}

/**
 * Returns formatted trilingual city name in strict order:
 * "English | සිංහල | தமிழ்"
 *
 * Example:
 * getTrilingualCity('Colombo') => 'Colombo | කොළඹ | கொழும்பு'
 * getTrilingualCity('Kandy')   => 'Kandy | මහනුවර | கண்டி'
 */
export function getTrilingualCity(rawName, separator = ' | ') {
  if (!rawName || typeof rawName !== 'string') return rawName || '';
  
  // If already formatted with separator or trilingual, return as-is
  if (rawName.includes(' | ') || (rawName.includes(' / ') && rawName.split('/').length >= 3)) {
    return rawName;
  }

  const obj = getCityTranslationObj(rawName);
  if (obj) {
    return `${obj.en}${separator}${obj.si}${separator}${obj.ta}`;
  }

  // Fallback to original name if unmapped
  return rawName;
}

